/*
 * کلید یکتای مقایسه‌ی نام مکان (تنها منبع حقیقت؛ worldMap.js هم از همین استفاده می‌کند).
 * این نوشته‌ها همگی یک مکان حساب می‌شوند:
 *   «مزرعهٔ سوخته» ، «مزرعۀ سوخته» ، «مزرعه‌ی سوخته» ، «مزرعه ی سوخته» ، «مزرعه سوخته»
 */
function locationKey(name) {
    return String(name || "")
        .replace(/\u06C0/g, "\u0647")                         // ۀ -> ه
        .replace(/[\u064B-\u065F\u0640\u200d\u200e\u200f]/g, "") // اعراب (شامل همزه‌ی ٔ)، کشیده و کاراکترهای جهت
        .replace(/[يى]/g, "ی")
        .replace(/ك/g, "ک")
        // کسره‌ی اضافه به شکل «ه ی» یا «ه‌ی» -> «ه»
        .replace(/\u0647[\s\u200c]+\u06CC(?=[\s\u200c]|$)/g, "\u0647")
        .replace(/[\s\u200c]+/g, "")
        .toLowerCase();
}

function getLocation(name) {
    const key = locationKey(name);
    if (!key) return null;
    return WORLD_LOCATIONS.find(l => locationKey(l.name) === key) || null;
}

function areAdjacent(a, b) {
    return WORLD_EDGES.some(([x, y]) =>
        (x === a && y === b) || (x === b && y === a)
    );
}

function neighbors(name) {
    return WORLD_EDGES
        .filter(([a, b]) => a === name || b === name)
        .map(([a, b]) => a === name ? b : a);
}

